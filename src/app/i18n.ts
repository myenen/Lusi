export const catalog = { en, tr };
export const LocaleContext = createContext<Locale>('en');

export function useLabels() {
  return catalog[useContext(LocaleContext)];
}

export function resolveLocale(preference: LanguagePreference, systemLocale: string | null): Locale {
  if (preference !== 'system') return preference;
  return systemLocale?.split(/[-_]/)[0]?.toLowerCase() === 'tr' ? 'tr' : 'en';
}
